#!/usr/bin/env bash
# Must Have — доступ с телефона в той же Wi-Fi сети.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PORT="${1:-8080}"
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"

if [ -z "${IP:-}" ]; then
  IP="<IP-компьютера>"
fi

cat <<TXT
Must Have — телефонный режим

1. Компьютер и телефон должны быть в одной Wi-Fi сети.
2. Не закрывайте этот терминал, пока пользуетесь приложением.
3. На телефоне откройте:

   http://${IP}:${PORT}/

   Если не открывается, проверьте файрвол и IP командой: hostname -I
4. Данные телефона хранятся в браузере телефона отдельно от компьютерных.
   Для переноса используйте «Дополнительно → Архив → Экспорт/Импорт».

Остановить сервер: Ctrl+C
TXT

exec python3 -m http.server "$PORT" --bind 0.0.0.0 --directory "$DIR"
